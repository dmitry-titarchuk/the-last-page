export function createPushkinPortrait(material) {
  const portrait = new THREE.Group();
  for (const stroke of strokes) {
    const points = stroke.map(([x, y]) => new THREE.Vector3((x - 407) / 1040, 0, (y - 397) / 1040));
    const curve = new THREE.CatmullRomCurve3(points, false, 'centripetal');
    const line = new THREE.Mesh(new THREE.TubeGeometry(curve, points.length * 6, .0028, 5, false), material);
    portrait.add(line);
  }
  return portrait;
}
